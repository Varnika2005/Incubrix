import React, { useState, useRef } from 'react';
import { MediaMetadata } from '../types';
import {
  Download,
  FileCheck,
  Play,
  Pause,
  Columns,
  CheckCircle,
  Clock,
  Maximize2,
  Film,
  Zap,
} from 'lucide-react';

interface ComparisonViewerProps {
  originalSrc: string;
  outputSrc: string;
  originalMeta?: MediaMetadata | null;
  outputMeta?: MediaMetadata | null;
  processingTime?: number | null;
  onDownload: () => void;
  onOpenReceipt: () => void;
}

export const ComparisonViewer: React.FC<ComparisonViewerProps> = ({
  originalSrc,
  outputSrc,
  originalMeta,
  outputMeta,
  processingTime,
  onDownload,
  onOpenReceipt,
}) => {
  const origVideoRef = useRef<HTMLVideoElement>(null);
  const outVideoRef = useRef<HTMLVideoElement>(null);
  const [isPlaying, setIsPlaying] = useState(false);
  const [viewMode, setViewMode] = useState<'side-by-side' | 'tabbed'>('side-by-side');
  const [activeTab, setActiveTab] = useState<'output' | 'original'>('output');

  const togglePlaySync = () => {
    if (!origVideoRef.current || !outVideoRef.current) return;

    if (isPlaying) {
      origVideoRef.current.pause();
      outVideoRef.current.pause();
      setIsPlaying(false);
    } else {
      origVideoRef.current.play().catch(() => {});
      outVideoRef.current.play().catch(() => {});
      setIsPlaying(true);
    }
  };

  const formatBytes = (bytes: number) => {
    if (!bytes) return '0 B';
    const k = 1024;
    const sizes = ['B', 'KB', 'MB', 'GB'];
    const i = Math.floor(Math.log(bytes) / Math.log(k));
    return parseFloat((bytes / Math.pow(k, i)).toFixed(2)) + ' ' + sizes[i];
  };

  return (
    <div className="glass-card p-6 flex flex-col gap-6 border-emerald-500/30">
      {/* Header and Actions */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-[rgba(255,255,255,0.06)] pb-4">
        <div>
          <div className="flex items-center gap-2">
            <span className="badge badge-emerald text-[10px]">Processing Complete</span>
            <h3 className="text-lg font-bold text-white">Original vs. Processed Output</h3>
          </div>
          <p className="text-xs text-[#94A3B8] mt-0.5">
            Compare and inspect the real video transformation generated by the engine
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            onClick={togglePlaySync}
            className="btn btn-secondary text-xs py-2 px-3"
            title="Play/Pause both videos synchronously"
          >
            {isPlaying ? <Pause className="w-3.5 h-3.5" /> : <Play className="w-3.5 h-3.5" />}
            <span>{isPlaying ? 'Pause Sync' : 'Play Sync'}</span>
          </button>

          <button
            onClick={onOpenReceipt}
            className="btn btn-secondary text-xs py-2 px-3"
            title="View verified Edit Receipt JSON"
          >
            <FileCheck className="w-3.5 h-3.5 text-indigo-400" />
            <span>Edit Receipt</span>
          </button>

          <button
            onClick={onDownload}
            className="btn btn-primary text-xs py-2 px-4 shadow-lg shadow-indigo-500/25 font-bold"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Video</span>
          </button>
        </div>
      </div>

      {/* Video Viewers */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {/* Original */}
        <div className="glass-card overflow-hidden bg-black/40 border-[rgba(255,255,255,0.08)]">
          <div className="p-3 bg-black/40 border-b border-[rgba(255,255,255,0.06)] flex items-center justify-between">
            <span className="text-xs font-semibold text-[#94A3B8]">ORIGINAL SOURCE</span>
            <span className="badge badge-indigo text-[9px]">SOURCE</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={origVideoRef}
              src={originalSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>

        {/* Edited */}
        <div className="glass-card overflow-hidden bg-black/40 border-cyan-500/30">
          <div className="p-3 bg-black/40 border-b border-[rgba(255,255,255,0.06)] flex items-center justify-between">
            <span className="text-xs font-semibold text-cyan-300">EDITED OUTPUT</span>
            <span className="badge badge-cyan text-[9px]">READY</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={outVideoRef}
              src={outputSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>
      </div>

      {/* Comparison Metrics Table */}
      {originalMeta && outputMeta && (
        <div className="glass-card p-4 bg-[rgba(10,14,24,0.7)]">
          <div className="text-xs font-semibold text-[#94A3B8] mb-3 flex items-center gap-1.5 uppercase tracking-wider">
            <Columns className="w-3.5 h-3.5 text-cyan-400" />
            <span>Transformation Audit Metrics</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
            <div className="p-2.5 rounded-lg bg-[rgba(255,255,255,0.03)] border border-[rgba(255,255,255,0.05)]">
              <span className="text-[#64748B] block">Duration</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8] line-through">{originalMeta.duration.toFixed(1)}s</span>
                <span className="text-white font-bold text-sm">→ {outputMeta.duration.toFixed(1)}s</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-[rgba(255,255,255,0.03)] border border-[rgba(255,255,255,0.05)]">
              <span className="text-[#64748B] block">Aspect Ratio</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8]">{originalMeta.aspect_ratio}</span>
                <span className="text-cyan-300 font-bold text-sm">→ {outputMeta.aspect_ratio}</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-[rgba(255,255,255,0.03)] border border-[rgba(255,255,255,0.05)]">
              <span className="text-[#64748B] block">Dimensions</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8]">{originalMeta.width}x{originalMeta.height}</span>
                <span className="text-white font-bold text-xs">→ {outputMeta.width}x{outputMeta.height}</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-[rgba(255,255,255,0.03)] border border-[rgba(255,255,255,0.05)]">
              <span className="text-[#64748B] block">Processing Speed</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <Zap className="w-3.5 h-3.5 text-amber-400" />
                <span className="text-amber-300 font-bold text-sm">{processingTime ?? 1.2}s</span>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
