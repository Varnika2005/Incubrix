import React, { useState, useRef } from 'react';
import { MediaMetadata } from '../types';
import {
  Download,
  FileCheck,
  Play,
  Pause,
  Columns,
  CheckCircle,
  Clock,
  Maximize2,
  Film,
  Zap,
  Trophy,
} from 'lucide-react';

interface ComparisonViewerProps {
  originalSrc: string;
  outputSrc: string;
  originalMeta?: MediaMetadata | null;
  outputMeta?: MediaMetadata | null;
  processingTime?: number | null;
  onDownload: () => void;
  onOpenReceipt: () => void;
}

export const ComparisonViewer: React.FC<ComparisonViewerProps> = ({
  originalSrc,
  outputSrc,
  originalMeta,
  outputMeta,
  processingTime,
  onDownload,
  onOpenReceipt,
}) => {
  const origVideoRef = useRef<HTMLVideoElement>(null);
  const outVideoRef = useRef<HTMLVideoElement>(null);
  const [isPlaying, setIsPlaying] = useState(false);

  const togglePlaySync = () => {
    if (!origVideoRef.current || !outVideoRef.current) return;

    if (isPlaying) {
      origVideoRef.current.pause();
      outVideoRef.current.pause();
      setIsPlaying(false);
    } else {
      origVideoRef.current.play().catch(() => {});
      outVideoRef.current.play().catch(() => {});
      setIsPlaying(true);
    }
  };

  const formatBytes = (bytes: number) => {
    if (!bytes) return '0 B';
    const k = 1024;
    const sizes = ['B', 'KB', 'MB', 'GB'];
    const i = Math.floor(Math.log(bytes) / Math.log(k));
    return parseFloat((bytes / Math.pow(k, i)).toFixed(2)) + ' ' + sizes[i];
  };

  return (
    <div
      className="glass-card p-6 flex flex-col gap-6 animate-fade-in-up"
      style={{
        borderColor: 'rgba(52,211,153,0.25)',
        background: 'linear-gradient(160deg, rgba(52,211,153,0.04) 0%, var(--bg-card) 30%), var(--bg-card)',
      }}
    >
      {/* Header and Actions */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-[rgba(255,255,255,0.06)] pb-5">
        <div>
          <div className="flex items-center gap-2.5">
            <span className="badge badge-emerald text-[10px]">
              <Trophy className="w-3 h-3" />
              Processing Complete
            </span>
            <h3 className="text-lg font-bold text-white">Original vs. Processed Output</h3>
          </div>
          <p className="text-xs text-[#64748B] mt-1">
            Compare and inspect the real video transformation generated by the engine
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            onClick={togglePlaySync}
            className="btn btn-secondary text-xs py-2 px-3.5"
            title="Play/Pause both videos synchronously"
          >
            {isPlaying ? <Pause className="w-3.5 h-3.5 text-amber-400" /> : <Play className="w-3.5 h-3.5 text-emerald-400" />}
            <span>{isPlaying ? 'Pause Sync' : 'Play Sync'}</span>
          </button>

          <button
            onClick={onOpenReceipt}
            className="btn btn-secondary text-xs py-2 px-3.5"
            title="View verified Edit Receipt JSON"
            style={{ borderColor: 'rgba(139,92,246,0.2)' }}
          >
            <FileCheck className="w-3.5 h-3.5 text-violet-400" />
            <span>Edit Receipt</span>
          </button>

          <button
            onClick={onDownload}
            className="btn text-xs py-2.5 px-5 font-bold"
            style={{
              background: 'linear-gradient(135deg, #34D399 0%, #22D3EE 100%)',
              color: '#fff',
              boxShadow: '0 6px 24px rgba(52,211,153,0.3)',
            }}
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Video</span>
          </button>
        </div>
      </div>

      {/* Video Viewers */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {/* Original */}
        <div
          className="glass-card overflow-hidden"
          style={{
            borderColor: 'rgba(139,92,246,0.2)',
            background: 'rgba(0,0,0,0.3)',
          }}
        >
          <div
            className="p-3.5 flex items-center justify-between"
            style={{
              background: 'rgba(0,0,0,0.4)',
              borderBottom: '1px solid rgba(255,255,255,0.05)',
            }}
          >
            <span className="text-xs font-bold text-[#94A3B8]">ORIGINAL SOURCE</span>
            <span className="badge badge-indigo text-[9px]">SOURCE</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={origVideoRef}
              src={originalSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>

        {/* Edited */}
        <div
          className="glass-card overflow-hidden"
          style={{
            borderColor: 'rgba(34,211,238,0.25)',
            background: 'rgba(0,0,0,0.3)',
          }}
        >
          <div
            className="p-3.5 flex items-center justify-between"
            style={{
              background: 'linear-gradient(90deg, rgba(34,211,238,0.05) 0%, transparent 100%)',
              borderBottom: '1px solid rgba(255,255,255,0.05)',
            }}
          >
            <span className="text-xs font-bold text-cyan-300">EDITED OUTPUT</span>
            <span className="badge badge-cyan text-[9px]">READY</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={outVideoRef}
              src={outputSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>
      </div>

      {/* Comparison Metrics Table */}
      {originalMeta && outputMeta && (
        <div
          className="glass-card p-5"
          style={{
            background: 'rgba(8,12,24,0.6)',
            borderColor: 'rgba(255,255,255,0.05)',
          }}
        >
          <div className="text-xs font-bold text-[#64748B] mb-4 flex items-center gap-2 uppercase tracking-wider">
            <Columns className="w-3.5 h-3.5 text-cyan-400" />
            <span>Transformation Audit Metrics</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs stagger-children">
            {[
              {
                label: 'Duration',
                from: `${originalMeta.duration.toFixed(1)}s`,
                to: `${outputMeta.duration.toFixed(1)}s`,
                color: '#A78BFA',
              },
              {
                label: 'Aspect Ratio',
                from: originalMeta.aspect_ratio,
                to: outputMeta.aspect_ratio,
                color: '#67E8F9',
              },
              {
                label: 'Dimensions',
                from: `${originalMeta.width}x${originalMeta.height}`,
                to: `${outputMeta.width}x${outputMeta.height}`,
                color: '#F9A8D4',
              },
              {
                label: 'Processing',
                from: null,
                to: `${processingTime ?? 1.2}s`,
                color: '#FBBF24',
                icon: <Zap className="w-3.5 h-3.5" style={{ color: '#FBBF24' }} />,
              },
            ].map((metric, i) => (
              <div
                key={i}
                className="p-3 rounded-xl transition-all hover:scale-105"
                style={{
                  background: 'rgba(255,255,255,0.02)',
                  border: '1px solid rgba(255,255,255,0.04)',
                }}
              >
                <span className="text-[#64748B] block">{metric.label}</span>
                <div className="mt-1.5 flex items-baseline gap-1.5">
                  {metric.from && (
                    <span className="text-[#94A3B8] line-through text-[11px]">{metric.from}</span>
                  )}
                  {metric.icon && metric.icon}
                  <span className="font-bold text-sm" style={{ color: metric.color }}>
                    {metric.from ? '→ ' : ''}{metric.to}
                  </span>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
