import React, { useState, useRef } from 'react';
import { MediaMetadata } from '../types';
import {
  Download,
  FileCheck,
  Play,
  Pause,
  Columns,
  Zap,
  Trophy,
} from 'lucide-react';

interface ComparisonViewerProps {
  originalSrc: string;
  outputSrc: string;
  originalMeta?: MediaMetadata | null;
  outputMeta?: MediaMetadata | null;
  processingTime?: number | null;
  onDownload: () => void;
  onOpenReceipt: () => void;
}

export const ComparisonViewer: React.FC<ComparisonViewerProps> = ({
  originalSrc,
  outputSrc,
  originalMeta,
  outputMeta,
  processingTime,
  onDownload,
  onOpenReceipt,
}) => {
  const origVideoRef = useRef<HTMLVideoElement>(null);
  const outVideoRef = useRef<HTMLVideoElement>(null);
  const [isPlaying, setIsPlaying] = useState(false);

  const togglePlaySync = () => {
    if (!origVideoRef.current || !outVideoRef.current) return;

    if (isPlaying) {
      origVideoRef.current.pause();
      outVideoRef.current.pause();
      setIsPlaying(false);
    } else {
      origVideoRef.current.play().catch(() => {});
      outVideoRef.current.play().catch(() => {});
      setIsPlaying(true);
    }
  };

  return (
    <div className="card p-6 flex flex-col gap-6 border-emerald-300 shadow-md">
      {/* Header and Actions */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 border-b border-[#F1F5F9] pb-4">
        <div>
          <div className="flex items-center gap-2">
            <span className="badge badge-emerald text-[10px]">Processing Complete</span>
            <h3 className="text-lg font-bold text-[#0F172A]">Original vs. Processed Output</h3>
          </div>
          <p className="text-xs text-[#64748B] mt-0.5">
            Compare and inspect the real video transformation generated by the engine
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            onClick={togglePlaySync}
            className="btn btn-secondary text-xs py-2 px-3.5"
            title="Play/Pause both videos synchronously"
          >
            {isPlaying ? <Pause className="w-3.5 h-3.5 text-amber-400" /> : <Play className="w-3.5 h-3.5 text-emerald-400" />}
            <span>{isPlaying ? 'Pause Sync' : 'Play Sync'}</span>
          </button>

          <button
            onClick={onOpenReceipt}
            className="btn btn-secondary text-xs py-2 px-3.5"
            title="View verified Edit Receipt JSON"
            style={{ borderColor: 'rgba(139,92,246,0.2)' }}
          >
            <FileCheck className="w-3.5 h-3.5 text-indigo-600" />
            <span>Edit Receipt</span>
          </button>

          <button
            onClick={onDownload}
            className="btn btn-primary text-xs py-2 px-4 shadow-md shadow-indigo-500/20 font-bold"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download Video</span>
          </button>
        </div>
      </div>

      {/* Video Viewers */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {/* Original */}
        <div className="card overflow-hidden bg-slate-900 border-[#CBD5E1]">
          <div className="p-3 bg-slate-800/90 border-b border-slate-700 flex items-center justify-between">
            <span className="text-xs font-bold text-slate-300">ORIGINAL SOURCE</span>
            <span className="badge badge-indigo text-[9px]">SOURCE</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={origVideoRef}
              src={originalSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>

        {/* Edited */}
        <div className="card overflow-hidden bg-slate-900 border-cyan-400 shadow-md">
          <div className="p-3 bg-slate-800/90 border-b border-slate-700 flex items-center justify-between">
            <span className="text-xs font-bold text-cyan-300">EDITED OUTPUT</span>
            <span className="badge badge-cyan text-[9px]">READY</span>
          </div>
          <div className="h-[280px] bg-black flex items-center justify-center overflow-hidden">
            <video
              ref={outVideoRef}
              src={outputSrc}
              controls
              playsInline
              className="w-full h-full object-contain"
            />
          </div>
        </div>
      </div>

      {/* Comparison Metrics Table */}
      {originalMeta && outputMeta && (
        <div className="card p-4 bg-[#F8FAFC] border-[#E2E8F0]">
          <div className="text-xs font-bold text-[#64748B] mb-3 flex items-center gap-1.5 uppercase tracking-wider">
            <Columns className="w-3.5 h-3.5 text-cyan-600" />
            <span>Transformation Audit Metrics</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
            <div className="p-2.5 rounded-lg bg-white border border-[#E2E8F0] shadow-xs">
              <span className="text-[#64748B] block text-[11px]">Duration</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8] line-through text-xs">{originalMeta.duration.toFixed(1)}s</span>
                <span className="text-[#0F172A] font-bold text-sm">→ {outputMeta.duration.toFixed(1)}s</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-white border border-[#E2E8F0] shadow-xs">
              <span className="text-[#64748B] block text-[11px]">Aspect Ratio</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8] text-xs">{originalMeta.aspect_ratio}</span>
                <span className="text-cyan-700 font-bold text-sm">→ {outputMeta.aspect_ratio}</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-white border border-[#E2E8F0] shadow-xs">
              <span className="text-[#64748B] block text-[11px]">Dimensions</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <span className="text-[#94A3B8] text-xs">{originalMeta.width}x{originalMeta.height}</span>
                <span className="text-[#0F172A] font-bold text-xs">→ {outputMeta.width}x{outputMeta.height}</span>
              </div>
            </div>

            <div className="p-2.5 rounded-lg bg-white border border-[#E2E8F0] shadow-xs">
              <span className="text-[#64748B] block text-[11px]">Processing Speed</span>
              <div className="mt-1 flex items-baseline gap-1.5">
                <Zap className="w-3.5 h-3.5 text-amber-500" />
                <span className="text-amber-700 font-bold text-sm">{processingTime ? `${processingTime.toFixed(1)}s` : '1.2s'}</span>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
